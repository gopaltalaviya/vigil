/**
 * Writes the VigilReceipts ABI as a typed TypeScript constant, from the compiled
 * contract. Run after changing the contract: `pnpm --filter @vigil/contracts build && pnpm gen:abi`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const path = (relative: string): string => fileURLToPath(new URL(relative, import.meta.url));
const artifact = JSON.parse(
  readFileSync(path("../contracts/out/VigilReceipts.sol/VigilReceipts.json"), "utf8"),
) as { abi: unknown };

const source = `// Generated by scripts/gen-abi.ts from contracts/src/VigilReceipts.sol. Do not edit by hand.
export const vigilReceiptsAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync(path("../packages/receipts/src/abi.ts"), source);
console.log("wrote packages/receipts/src/abi.ts");
